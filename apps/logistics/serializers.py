class DeliveryQueueItemSerializer(serializers.ModelSerializer):
    """Single item in a rider's delivery queue."""
    order_number = serializers.CharField(source='order.order_number', read_only=True)
    customer_phone = serializers.CharField(source='order.customer_phone', read_only=True)
    delivery_address = serializers.CharField(source='order.delivery_address', read_only=True)
    branch = serializers.CharField(source='order.branch.name', read_only=True)
    items = serializers.SerializerMethodField()

    class Meta:
        model = DeliveryAssignment
        fields = [
            'id', 'order_number', 'customer_phone',
            'delivery_address', 'branch', 'status',
            'assigned_at', 'items',
        ]

    def get_items(self, obj):
        return [
            {
                'name': (
                    str(item.variant) if item.variant
                    else item.product.name
                ),
                'quantity': item.quantity,
            }
            for item in obj.order.items.all()
        ]


