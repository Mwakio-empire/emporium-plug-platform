class UpdateDeliveryStatusSerializer(serializers.Serializer):
    """
    Validates the payload for RiderUpdateDeliveryStatusView.
    Both latitude and longitude must be provided together, or neither.
    """
    status = serializers.ChoiceField(choices=DeliveryAssignment.DeliveryStatus.choices)
    latitude = serializers.DecimalField(
        max_digits=9, decimal_places=6, required=False, allow_null=True,
    )
    longitude = serializers.DecimalField(
        max_digits=9, decimal_places=6, required=False, allow_null=True,
    )
    notes = serializers.CharField(required=False, allow_blank=True)

    def validate(self, data):
        lat = data.get('latitude')
        lng = data.get('longitude')
        if (lat is None) != (lng is None):
            raise serializers.ValidationError(
                "Both latitude and longitude must be provided together, or neither."
            )
        return data


class PickupCodeSerializer(serializers.Serializer):
    """
    Validates the payload for ConfirmPickupView.
    Enforces exactly 6 uppercase alphanumeric characters — matches the
    format generated by OnlineOrderService._generate_pickup_code().
    """
    pickup_code = serializers.RegexField(
        regex=r'^[A-Za-z0-9]{6}$',
        error_messages={
            'invalid': 'Pickup code must be exactly 6 characters.'
        },
    )

    def validate_pickup_code(self, value):
        return value.strip().upper()
