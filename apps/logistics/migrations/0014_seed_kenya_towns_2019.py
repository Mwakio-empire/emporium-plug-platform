def normalize_name(value):
    display_name = ' '.join(unicodedata.normalize('NFKC', value).split())
    return display_name, display_name.casefold()


def seed_kenya_towns(apps, schema_editor):
    Town = apps.get_model('logistics', 'KenyaTown')
    for source_name, source_county in URBAN_CENTRES:
        name, normalized_name = normalize_name(source_name)
        for county_code in COUNTY_CODES[source_county]:
            Town.objects.get_or_create(
                county_id=county_code,
                normalized_name=normalized_name,
                defaults={
                    'name': name,
                    'is_active': True,
                    'source': SOURCE,
                    'source_revision': SOURCE_REVISION,
                },
            )


def remove_seeded_kenya_towns(apps, schema_editor):
    Town = apps.get_model('logistics', 'KenyaTown')
    Town.objects.filter(
        source=SOURCE,
        source_revision=SOURCE_REVISION,
    ).delete()


